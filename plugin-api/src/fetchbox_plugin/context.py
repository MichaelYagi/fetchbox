"""``ctx``: what every plugin method receives, the only way it talks to Fetchbox.

These are the types (for editors and mypy); Fetchbox passes the real thing. Anything a
plugin reaches past ``ctx`` for is internal to Fetchbox and may change in any release.
"""

from __future__ import annotations

from collections.abc import Awaitable, Callable
from pathlib import Path
from typing import Any, Protocol, TypeVar

import httpx

from fetchbox_plugin.types import FileInfo, SidecarInfo, TitleInfo

T = TypeVar("T")


class Http(Protocol):
    """Fetchbox's timeouts, retries for GETs, a User-Agent naming the plugin, and per-host
    rate limits: ``ctx.http.limit("api.example.com", per_second=1)``."""

    def limit(self, host: str, *, per_second: float) -> None: ...
    async def request(self, method: str, url: str, **kwargs: Any) -> httpx.Response: ...
    async def get(self, url: str, **kwargs: Any) -> httpx.Response: ...
    async def post(self, url: str, **kwargs: Any) -> httpx.Response: ...


class Cache(Protocol):
    """Answers kept for a while (in memory)."""

    def get(self, key: str, default: Any = None) -> Any: ...
    def set(self, key: str, value: Any, seconds: float) -> None: ...
    async def remember(self, key: str, seconds: float, fetch: Callable[[], Awaitable[T]]) -> T: ...
    def clear(self) -> None: ...


class Store(Protocol):
    """A small key-value store, kept in Fetchbox's database (in backups). JSON values, up to
    64 KB each; bigger things go in ``ctx.folder``."""

    async def get(self, key: str, default: Any = None) -> Any: ...
    async def set(self, key: str, value: Any) -> None: ...
    async def delete(self, key: str) -> bool: ...
    async def keys(self, prefix: str = "") -> list[str]: ...


class Files(Protocol):
    """A library file's place on disk, and sidecar files: written beside a file and from then
    on renamed, moved, recycled and deleted with it."""

    async def path(self, file_id: str) -> Path: ...
    async def sidecars(self, file_id: str, *, suffix: str | None = None) -> list[SidecarInfo]: ...
    async def add_sidecar(
        self, file_id: str, suffix: str, data: bytes, *, meta: dict[str, Any] | None = None
    ) -> SidecarInfo: ...
    async def remove_sidecar(self, file_id: str, suffix: str) -> bool: ...


class Library(Protocol):
    """Titles and their files, read-only; wanting and searching go through the same rules
    and events as the web UI."""

    async def titles(self, *, kind: str | None = None) -> list[TitleInfo]: ...
    async def title(self, title_id: str) -> TitleInfo: ...
    async def files(self, title_id: str) -> list[FileInfo]: ...
    async def file(self, file_id: str) -> FileInfo: ...
    async def wanted(self, item_id: str, monitored: bool = True) -> None: ...
    async def search(self, item_id: str) -> str | None: ...


class Job(Protocol):
    """A running job: its payload, and how it reports progress."""

    payload: dict[str, Any]

    async def progress(self, value: float, message: str | None = None) -> None: ...
    async def check_cancelled(self) -> None: ...


class Jobs(Protocol):
    def job(self, name: str, *, max_attempts: int = 3) -> Callable[[Any], Any]: ...
    async def enqueue(
        self, name: str, payload: dict[str, Any] | None = None, *, dedupe_key: str | None = None
    ) -> str | None: ...


class Notify(Protocol):
    async def __call__(self, title: str, body: str = "", *, level: str = "info") -> int: ...


class Context(Protocol):
    plugin_id: str
    log: Any  # a structlog logger tagged with the plugin's id: ctx.log.info("synced", n=3)

    @property
    def http(self) -> Http: ...
    @property
    def cache(self) -> Cache: ...
    @property
    def store(self) -> Store: ...
    @property
    def folder(self) -> Path: ...
    @property
    def files(self) -> Files: ...
    @property
    def library(self) -> Library: ...
    @property
    def jobs(self) -> Jobs: ...
    @property
    def notify(self) -> Notify: ...
